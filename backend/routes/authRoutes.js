const router = require('express').Router();
const auth = require('../middleware/auth');
const c = require('../controllers/authController');
router.post('/register', c.register);
router.post('/login', c.login);
router.post('/forgot-password', c.forgot);
router.post('/reset-password', c.reset);
router.post('/verify-email', c.verify);
router.use(auth, auth.sessionOnly);
router.get('/me', c.me);
router.put('/me', c.updateMe);
router.post('/request-verification', c.requestVerification);
router.post('/change-password', c.changePassword);
module.exports = router;
