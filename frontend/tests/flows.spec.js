import { test, expect } from '@playwright/test';
const apiBase = 'http://127.0.0.1:5055';
test('register, create, edit, pause, resume and export analytics', async ({ page, request }) => {
  await page.goto('/register');
  await page.getByLabel('Full Name').fill('Browser Tester');
  await page.getByLabel('Email', { exact: true }).fill('browser@example.com');
  await page.getByLabel('Password', { exact: true }).fill('BrowserPassword!');
  await page.getByLabel('Confirm Password').fill('BrowserPassword!');
  await page.locator('#agree').check();
  await page.getByRole('button', { name: 'Sign Up', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Shorten, Track & Analyze Your Links' })).toBeVisible();
  await page.getByPlaceholder('Paste a long URL to shorten...').fill('https://example.com/quick');
  await page.getByRole('button', { name: 'Shorten URL', exact: true }).click();
  await expect(page.getByText('Link shortened successfully:')).toBeVisible();
  await page.screenshot({ path: 'test-results/dashboard-desktop.png', fullPage: true });
  await page.goto('/shorten');
  await page.getByRole('button', { name: 'New Link', exact: true }).click();
  await page.getByLabel('Destination URL').fill('https://example.com/first');
  await page.getByLabel('Title', { exact: true }).fill('Browser link');
  await page.getByLabel('Custom alias').fill('browser-link');
  await page.getByText('Campaign parameters (optional)').click();
  await page.getByLabel('Campaign source', { exact: true }).fill('newsletter');
  await page.getByRole('button', { name: 'Save link', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.goto('/shorten');
  const row = page.getByRole('row').filter({ hasText: 'Browser link' });
  await expect(row).toBeVisible();
  await page.getByLabel('Sort links by').selectOption('title');
  await expect(row).toBeVisible();
  const campaignRedirect = await request.get(apiBase + '/browser-link', { maxRedirects: 0 });
  expect(campaignRedirect.headers().location).toBe('https://example.com/first?utm_source=newsletter');
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByLabel('Destination URL').fill('https://example.com/updated');
  await page.getByRole('button', { name: 'Save link', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await page.getByText('Change history', { exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('originalUrl');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await row.getByRole('button', { name: 'Pause', exact: true }).click();
  await expect(row.getByRole('button', { name: 'Resume', exact: true })).toBeVisible();
  const paused = await request.get(apiBase + '/browser-link', { maxRedirects: 0 });
  expect(paused.headers().location).toContain('reason=paused');
  await row.getByRole('button', { name: 'Resume', exact: true }).click();
  await expect(row.getByRole('button', { name: 'Pause', exact: true })).toBeVisible();
  const redirect = await request.get(apiBase + '/browser-link', { maxRedirects: 0 });
  expect(redirect.status()).toBe(302); expect(redirect.headers().location).toBe('https://example.com/updated');
  await page.screenshot({ path: 'test-results/links-desktop.png', fullPage: true });
  await row.getByRole('button', { name: 'Stats', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Link Performance' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Export CSV' })).toBeEnabled();
  await expect(page.getByRole('heading', { name: 'Estimated unique visitors' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Avg. link age at click' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Operating Systems', exact: true }).first()).toBeVisible();
  await page.getByLabel('Date range', { exact: true }).selectOption('7');
  await expect(page.getByLabel('Date range', { exact: true })).toHaveValue('7');
  await page.getByLabel('Group by', { exact: true }).selectOption('week');
  await page.getByRole('button', { name: 'Apply dates', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Weekly Click Timeline' })).toBeVisible();
  await page.screenshot({ path: 'test-results/analytics-desktop.png', fullPage: true });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await downloadPromise).suggestedFilename()).toBe('sniply-clicks.csv');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'Estimated unique visitors' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/analytics-mobile.png', fullPage: true });
});

test('public incorrect password stays on unlock; email verify and reset work', async ({ page, request }) => {
  const r = await request.post(apiBase + '/api/v1/auth/register', { data: { name: 'Recovery', email: 'recovery@example.com', password: 'OriginalPassword!' } });
  const user = await r.json();
  const headers = { Authorization: 'Bearer ' + user.token };
  await request.post(apiBase + '/api/v1/links', { headers, data: { originalUrl: 'https://example.com', slug: 'protected-browser', password: 'ProtectedPassword!' } });
  await page.goto('/unlock/protected-browser');
  await page.evaluate(({ token, user }) => {
    localStorage.setItem('token', token);
    localStorage.setItem('user', JSON.stringify(user));
  }, user);
  await page.reload();
  const sessionBefore = await page.evaluate(() => ({ token: localStorage.getItem('token'), user: localStorage.getItem('user') }));
  await page.getByPlaceholder('Password', { exact: true }).fill('wrong');
  await page.getByRole('button', { name: 'Unlock & continue' }).click();
  await expect(page.getByText('Incorrect password')).toBeVisible();
  await expect(page).toHaveURL(/\/unlock\//);
  expect(await page.evaluate(() => ({ token: localStorage.getItem('token'), user: localStorage.getItem('user') }))).toEqual(sessionBefore);

  await request.post(apiBase + '/api/v1/auth/request-verification', { headers, data: {} });
  let mails = await (await request.get(apiBase + '/__test/mail')).json();
  await page.goto(mails.at(-1).text.match(/http[^\s]+/)[0]);
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Email verified');

  await page.goto('/forgot-password');
  await page.getByLabel('Email', { exact: true }).fill('recovery@example.com');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('If an eligible account exists');
  mails = await (await request.get(apiBase + '/__test/mail')).json();
  await page.goto(mails.at(-1).text.match(/http[^\s]+/)[0]);
  await page.getByLabel('New password', { exact: true }).fill('ChangedPassword!');
  await page.getByLabel('Confirm password', { exact: true }).fill('ChangedPassword!');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Password reset');
  await page.getByRole('link', { name: 'Back to login' }).click();
  await page.getByLabel('Email', { exact: true }).fill('recovery@example.com');
  await page.getByLabel('Password', { exact: true }).fill('ChangedPassword!');
  await page.getByRole('button', { name: 'Log In', exact: true }).click();
  await expect(page).toHaveURL('http://127.0.0.1:5175/');
});

test('API key management and mobile link dialog', async ({ page, request }) => {
  await request.post(apiBase + '/api/v1/auth/register', { data: { name: 'Key User', email: 'keys@example.com', password: 'BrowserPassword!' } });
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('browser@example.com');
  await page.getByLabel('Password', { exact: true }).fill('BrowserPassword!');
  await page.getByRole('button', { name: 'Log In', exact: true }).click();
  await expect(page).toHaveURL('http://127.0.0.1:5175/');
  await page.goto('/api');
  await page.getByLabel('Name', { exact: true }).fill('Browser key');
  await page.getByRole('button', { name: 'Create key', exact: true }).click();
  await expect(page.getByText('Copy your key now')).toBeVisible();
  await page.getByRole('button', { name: 'Hide key', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Revoke', exact: true }).click();
  await expect(page.getByText('Key revoked.', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/api-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/shorten');
  await page.getByRole('button', { name: 'New Link', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  const box = await dialog.boundingBox(); expect(box.width).toBeLessThanOrEqual(390);
  await dialog.screenshot({ path: 'test-results/link-editor-mobile.png' });
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'New Link', exact: true })).toBeFocused();
});

test('profile preferences persist and QR creation/download remain connected', async ({ page, request }) => {
  await request.post(apiBase + '/api/v1/auth/register', { data: { name: 'QR User', email: 'qr@example.com', password: 'BrowserPassword!' } });
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill('qr@example.com');
  await page.getByLabel('Password', { exact: true }).fill('BrowserPassword!');
  await page.getByRole('button', { name: 'Log In', exact: true }).click();
  await expect(page).toHaveURL('http://127.0.0.1:5175/');
  await page.goto('/settings');
  await page.getByLabel('company', { exact: true }).fill('Example Company');
  await page.getByLabel('timezone', { exact: true }).selectOption('Asia/Kolkata');
  await page.getByRole('button', { name: 'Save Changes', exact: true }).first().click();
  await expect(page.getByRole('status')).toHaveText('Profile saved.');
  await page.reload();
  await expect(page.getByLabel('company', { exact: true })).toHaveValue('Example Company');
  await expect(page.getByLabel('timezone', { exact: true })).toHaveValue('Asia/Kolkata');
  await page.screenshot({ path: 'test-results/settings-desktop.png', fullPage: true });
  await page.goto('/qr-codes');
  await page.getByRole('button', { name: 'Generate QR Code', exact: true }).click();
  await page.getByPlaceholder('https://example.com/very/long/destination/url').fill('https://example.com/qr');
  await page.getByRole('button', { name: 'Create & Select', exact: true }).click();
  await expect(page.getByRole('img', { name: 'QR Code', exact: true })).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download PNG', exact: true }).click();
  expect((await downloadPromise).suggestedFilename()).toMatch(/-qr\.png$/);
  await page.getByRole('button', { name: 'Generate QR Code', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Create & Select', exact: true })).toBeEnabled();
  await page.goto('/settings');
  await page.getByRole('button', { name: 'Security', exact: true }).click();
  await page.getByRole('button', { name: 'Send verification email', exact: true }).click();
  await expect(page.getByRole('status')).toBeVisible();
  await page.getByLabel('Current password', { exact: true }).fill('BrowserPassword!');
  await page.getByLabel('New password', { exact: true }).fill('UpdatedBrowserPassword!');
  await page.getByLabel('Confirm new password', { exact: true }).fill('UpdatedBrowserPassword!');
  await page.getByRole('button', { name: 'Change password and sign out' }).click();
  await expect(page).toHaveURL(/\/login$/);
});
